package ai.yuriilab.recursivecoder

/**
 * In-memory, host-owned stage-graph contract. These values are NOT a wire protocol and
 * are never grants of authority merely because an agent produced matching JSON/text.
 */
@JvmInline value class GraphId(val value: String) {
    init { require(ToolAuthorizationPolicy.validHostIdentifier(value)) { "Invalid graph ID" } }
}

@JvmInline value class StageRunId(val value: String) {
    init { require(ToolAuthorizationPolicy.validHostIdentifier(value)) { "Invalid stage ID" } }
}

@JvmInline value class ArtifactId(val value: String) {
    init { require(ToolAuthorizationPolicy.validHostIdentifier(value)) { "Invalid artifact ID" } }
}

@JvmInline value class AgentId(val value: String) {
    init { require(ToolAuthorizationPolicy.validHostIdentifier(value)) { "Invalid agent ID" } }
}

enum class StageArtifactKind { REQUIREMENTS, ACCEPTANCE_TESTS, UNIT_TESTS, IMPLEMENTATION }

/**
 * Every role has a separate identity and explicit input/output contract.
 * REVIEW outputs a typed verdict, not an artifact that can approve itself.
 */
enum class StageKind(
    val role: EngineeringRole,
    val requiredInputs: Set<StageArtifactKind>,
    val output: StageArtifactKind?
) {
    SDD(EngineeringRole.SDD, emptySet(), StageArtifactKind.REQUIREMENTS),
    ATDD(EngineeringRole.ATDD, setOf(StageArtifactKind.REQUIREMENTS),
        StageArtifactKind.ACCEPTANCE_TESTS),
    TDD(EngineeringRole.TDD, setOf(StageArtifactKind.REQUIREMENTS,
        StageArtifactKind.ACCEPTANCE_TESTS), StageArtifactKind.UNIT_TESTS),
    DEVELOP(EngineeringRole.DEVELOPER, setOf(StageArtifactKind.REQUIREMENTS,
        StageArtifactKind.ACCEPTANCE_TESTS, StageArtifactKind.UNIT_TESTS),
        StageArtifactKind.IMPLEMENTATION),
    REVIEW(EngineeringRole.REVIEWER, StageArtifactKind.entries.toSet(), null)
}

enum class StageState { CREATED, READY, RUNNING, ACCEPTED, REJECTED, FAILED, CANCELLED }
enum class StageGraphState { CREATED, RUNNING, SUCCEEDED, FAILED, CANCELLED }
enum class ArtifactApproval { DRAFT, ACCEPTED, REJECTED }
enum class ArtifactFreeze { EDITABLE, FROZEN }
enum class ReviewVerdict { ACCEPT, REQUEST_CHANGES, REJECT }

/** IDs are generated by the host and correlated with the existing Session Protocol v1. */
data class GraphCorrelation(
    val sessionId: String,
    val graphId: GraphId,
    val correlationId: String,
    val causationId: String? = null,
    val parentGraphId: GraphId? = null,
    val parentStageRunId: StageRunId? = null
)

data class StageCorrelation(
    val sessionId: String,
    val graphId: GraphId,
    val stageRunId: StageRunId,
    val requestId: String,
    val correlationId: String,
    val causationId: String? = null
)

/**
 * Revision is monotonic within an artifact ID; a revision produces a new manifest value.
 * A digest pins bytes, not their trust or approval. Acceptance and freezing are host facts.
 */
data class StageArtifactManifest(
    val id: ArtifactId,
    val kind: StageArtifactKind,
    val declaredPath: String,
    val sha256: String,
    val ownerRole: EngineeringRole,
    val producerStageRunId: StageRunId,
    val revision: Long,
    val approval: ArtifactApproval,
    val freeze: ArtifactFreeze
)

/** Agent verdict is only a proposal until separately verified by the host. */
data class StageReviewDecision(
    val targetStageRunId: StageRunId,
    val implementationArtifactId: ArtifactId,
    val reviewedSha256: String,
    val requestedBy: AgentId,
    val reviewedBy: AgentId,
    val verdict: ReviewVerdict
)

data class StageNode(
    val correlation: StageCorrelation,
    val kind: StageKind,
    val state: StageState = StageState.CREATED,
    val agentId: AgentId? = null,
    val dependencies: Set<StageRunId> = emptySet(),
    val inputArtifacts: Set<ArtifactId> = emptySet(),
    val outputArtifacts: Set<ArtifactId> = emptySet(),
    val review: StageReviewDecision? = null
)

/**
 * Metadata for later child scheduling: no recursion, clock, budget spending or
 * dependency traversal is performed by this data class.
 */
data class StageBudget(
    val maxTokens: Long,
    val maxDurationMillis: Long,
    val maxDepth: Int,
    val maxChildren: Int
)

data class ChildGraphReference(
    val graphId: GraphId,
    val parentStageRunId: StageRunId,
    val dependsOnStages: Set<StageRunId>,
    val depth: Int,
    val budget: StageBudget
)

data class StageGraph(
    val correlation: GraphCorrelation,
    val state: StageGraphState,
    val stages: List<StageNode>,
    val artifacts: List<StageArtifactManifest>,
    val budget: StageBudget,
    val children: List<ChildGraphReference> = emptyList()
)

/**
 * Host-verified independent review of a revision, scoped and pinned to the
 * existing manifest. The caller must validate provenance before constructing it.
 */
data class StageRevisionAuthorization(
    val artifactId: ArtifactId,
    val expectedSha256: String,
    val expectedRevision: Long,
    val review: ReviewedChangeFacts
)

sealed interface StageGateDecision {
    data object Permit : StageGateDecision
    data class Deny(val code: String) : StageGateDecision
}
